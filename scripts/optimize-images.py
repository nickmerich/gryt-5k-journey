#!/usr/bin/env python3
"""Generate right-sized WebP variants of Lovable remote image assets.

Downloads each original listed in src/assets/*.asset.json from the live site
(https://grytrun.com + asset url), writes public/img/<stem>-<width>.webp and
regenerates src/lib/image-manifest.ts, which src/lib/responsive-image.ts reads.

Run: python3 scripts/optimize-images.py   (needs Pillow with WebP; curl)
Re-run after adding or replacing an image asset.
"""
import glob, json, os, re, subprocess, sys, tempfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "img")
CACHE = os.path.join(tempfile.gettempdir(), "gryt-img-originals")
ORIGIN = "https://grytrun.com"

# Target widths per asset (filename regex -> widths). First match wins.
# AVIF (smaller, with WebP fallback via <picture>) is only made for LCP heroes.
AVIF = {r"^rtwl-group-1920\.webp$", r"^rtwl-flyer\.png$"}
STEMS = {"rtwl-group-1920.webp": "rtwl-group"}
RULES = [
    (r"^rtwl-group-1920\.webp$", [480, 800, 1080, 1440, 1920]),
    (r"^rtwl-group-(720|1200)\.webp$", None),  # superseded by the 1920 master
    (r"^rtwl-group-finishers\.jpg$", [400, 800]),
    (r"^rtwl-img-8082\.jpg$", [400, 800, 1200]),
    (r"^rtwl-twl5k-.*\.jpg$", [400, 800]),
    (r"^rtwl-flyer\.png$", [400, 640, 960, 1280]),
    (r"^img-(creek|shelter|vinyl)\.webp$", [480, 800, 1200, 1600]),
    (r"^rtwl-recap-poster\.jpg$", [960]),
    (r"^gryt-bear\.png$", [64, 128, 192]),
    (r"^(oddisee|heno)-avatar\..*$", [64, 128, 192]),
    (r"^from-takoma-cover\.jpg$", [400, 700]),
    (r"^press-.*\.png$", [440]),
]
QUALITY = 74
AVIF_QUALITY = 55


def widths_for(name):
    for pat, ws in RULES:
        if re.match(pat, name):
            return ws
    return None


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(CACHE, exist_ok=True)
    manifest = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "src", "assets", "*.asset.json"))):
        d = json.load(open(f))
        name = d["original_filename"]
        ws = widths_for(name)
        if not ws or not d["content_type"].startswith("image/"):
            continue
        src = os.path.join(CACHE, name)
        if not os.path.exists(src) or os.path.getsize(src) != d["size"]:
            subprocess.run(["curl", "-sfL", "-A", "Mozilla/5.0", "-o", src, ORIGIN + d["url"]], check=True)
        im = Image.open(src)
        im.load()
        has_alpha = im.mode in ("RGBA", "LA") or (im.mode == "P" and "transparency" in im.info)
        im = im.convert("RGBA" if has_alpha else "RGB")
        W, H = im.size
        stem = STEMS.get(name, os.path.splitext(name)[0])
        avif = any(re.match(p, name) for p in AVIF)
        done = []
        for w in sorted({min(w, W) for w in ws}):
            h = round(H * w / W)
            out = os.path.join(OUT, f"{stem}-{w}.webp")
            r = im.resize((w, h), Image.LANCZOS)
            r.save(out, "WEBP", quality=QUALITY, method=6)
            if avif:
                r.save(out[:-5] + ".avif", "AVIF", quality=AVIF_QUALITY, speed=4)
            done.append(w)
        manifest[d["url"]] = {"stem": stem, "w": W, "h": H, "widths": done, "avif": avif}
        print(f"{name}: {W}x{H} -> {done}", file=sys.stderr)
    lines = [
        "// Generated by scripts/optimize-images.py. Do not edit by hand.",
        "// Maps Lovable asset URLs to locally served WebP variants in /public/img.",
        "export type ImageVariant = { stem: string; w: number; h: number; widths: number[]; avif: boolean };",
        "export const IMAGE_MANIFEST: Record<string, ImageVariant> = {",
    ]
    for url, v in manifest.items():
        lines.append(f"  {json.dumps(url)}: {json.dumps(v, separators=(', ', ': '))},")
    lines.append("};\n")
    open(os.path.join(ROOT, "src", "lib", "image-manifest.ts"), "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
